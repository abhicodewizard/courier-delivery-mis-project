"""
Stage 5 - Run every query in sql/03_business_queries.sql, save the results, and
cross-check key results against the Pandas analysis.

Run from the scripts/ folder:  python 05_run_sql_queries.py
Output: ../outputs/sql_results/Q01_*.csv ... and sql_results_summary.md
"""
import os
import re
import sqlite3

import pandas as pd

DB = "../database/courier_mis.db"
SQL_FILE = "../sql/03_business_queries.sql"
OUT = "../outputs/sql_results"
os.makedirs(OUT, exist_ok=True)

text = open(SQL_FILE).read()
blocks = re.split(r"(?m)^-- Q(\d+): (.*)$", text)
queries = [(int(blocks[i]), blocks[i + 1].strip(), blocks[i + 2].strip()) for i in range(1, len(blocks), 3)]

con = sqlite3.connect(DB)
results, md = {}, ["# SQL query results\n", "Generated by `scripts/05_run_sql_queries.py`.\n"]
for num, title, body in queries:
    df = pd.read_sql_query(body, con)
    results[num] = df
    slug = re.sub(r"[^a-z0-9]+", "_", title.lower()).strip("_")[:45]
    df.to_csv(f"{OUT}/Q{num:02d}_{slug}.csv", index=False)
    comments = "\n".join(l[3:] for l in body.splitlines() if l.startswith("-- "))
    md += [f"\n## Q{num}: {title}\n", comments + "\n", df.head(15).to_markdown(index=False) + "\n"]
    print(f"Q{num:02d} ok  {len(df):3d} rows  {title}")
open(f"{OUT}/sql_results_summary.md", "w").write("\n".join(md))

# ---- validation against the Pandas outputs ------------------------------------
py = pd.read_csv("../outputs/python_eda/kpis.csv").set_index("KPI")["Value"]
q1 = results[1].iloc[0]
assert q1["total_shipments"] == py["Total Shipments"] and q1["delivered"] == py["Delivered"]
assert q1["rto"] == py["RTO"] and q1["on_time"] == py["On-Time Deliveries"]
assert abs(q1["on_time_pct"] - py["On-Time Delivery %"]) < 0.01
assert abs(q1["avg_transit_days"] - py["Avg Transit Days"]) < 0.01
assert abs(q1["rto_pct"] - py["RTO %"]) < 0.01
assert abs(q1["total_freight_revenue"] - py["Total Freight Revenue"]) < 1

py_br = pd.read_csv("../outputs/python_eda/by_dest_branch.csv").set_index("Destination City")["On-Time %"]
sql_br = results[4].set_index("dest_city")["on_time_pct"]
assert all(abs(sql_br[c] - py_br[c]) < 0.01 for c in py_br.index), "branch on-time % differs"

py_sv = pd.read_csv("../outputs/python_eda/by_service.csv").set_index("Service Type")["On-Time %"]
sql_sv = results[3].set_index("service_type")["on_time_pct"]
assert all(abs(sql_sv[c] - py_sv[c]) < 0.01 for c in py_sv.index), "service on-time % differs"

py_rs = pd.read_csv("../outputs/python_eda/reasons.csv").set_index("Delay/Return Reason")["Delivered"]
sql_rs = results[13].set_index("reason")["late_shipments"]
assert all(sql_rs[c] == py_rs[c] for c in sql_rs.index), "late-reason counts differ"
print("\nValidation passed: SQL results match the Pandas results (KPIs, services, branches, delay reasons).")
con.close()
